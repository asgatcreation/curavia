"""Render the permissions matrix as Markdown, for the README."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from django.core.management.base import BaseCommand

from apps.core.matrix import as_markdown_table, load_matrix


class Command(BaseCommand):
    help = (
        "Generate the permissions matrix table from docs/permissions-matrix.yml, "
        "so the README cannot drift from what the code enforces."
    )

    def add_arguments(self, parser: Any) -> None:
        parser.add_argument("--output", help="Write to this file instead of stdout.")

    def handle(self, *args: Any, **options: Any) -> None:
        matrix = load_matrix()
        header = (
            "<!-- Generated by `manage.py export_permissions_matrix`. "
            "Do not edit by hand. Source: docs/permissions-matrix.yml "
            f"(version {matrix.version}). -->\n\n"
        )
        content = header + as_markdown_table() + "\n"

        output = options["output"]
        if output:
            Path(output).write_text(content, encoding="utf-8")
            self.stdout.write(
                self.style.SUCCESS(
                    f"Wrote {len(matrix.entries)} permissions x "
                    f"{len(matrix.roles)} roles to {output}"
                )
            )
        else:
            self.stdout.write(content)
