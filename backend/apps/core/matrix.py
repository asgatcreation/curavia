"""
The permissions matrix, loaded from one file.

``docs/permissions-matrix.yml`` states, for every permission code, which roles
are allowed to hold it. That single file has three jobs:

1. **The test suite.** ``tests/permissions`` parametrises over every
   (permission x role) pair and asserts the real engine agrees — and, where an
   endpoint is declared, that the real HTTP response is 200 or 403 to match.
2. **The README table**, generated by ``manage.py export_permissions_matrix``,
   so the documentation cannot drift from the code.
3. **The in-app role editor**, which shows an owner what a role can do.

The expectations are written **by hand, from intent** — never derived from the
role templates. Deriving them would make the test tautological: it would prove
only that the code matches itself. Because they are independent, changing a
role template fails the suite, which is exactly what should happen when
somebody widens a cashier's access.

Any role not in a permission's ``allow`` list is expected to be **denied**. So
adding a role to the system without considering each permission makes the suite
fail rather than quietly granting nothing — or quietly granting everything.
"""

from __future__ import annotations

import functools
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml
from django.conf import settings

from .permissions import ALL_PERMISSION_CODES


@dataclass(frozen=True, slots=True)
class Endpoint:
    """An API route that enforces a permission, so the test can call it."""

    method: str
    url_name: str
    #: Keyword arguments for ``reverse``, if the route takes any.
    kwargs: dict[str, Any] | None = None
    #: Expected status when allowed — 200 unless the view redirects or creates.
    allowed_status: int = 200
    #: Expected status when denied. 403 for a permission failure; 404 where
    #: revealing that the object exists would itself be a leak.
    denied_status: int = 403


@dataclass(frozen=True, slots=True)
class MatrixEntry:
    permission: str
    allow: frozenset[str]
    note: str = ""
    endpoint: Endpoint | None = None

    def expected(self, role: str) -> bool:
        return role in self.allow


@dataclass(frozen=True, slots=True)
class Matrix:
    version: int
    roles: tuple[str, ...]
    entries: tuple[MatrixEntry, ...]

    def by_permission(self, code: str) -> MatrixEntry | None:
        return next((entry for entry in self.entries if entry.permission == code), None)

    def pairs(self) -> list[tuple[MatrixEntry, str, bool]]:
        """Every (entry, role, expected) triple — what the test iterates over."""
        return [
            (entry, role, entry.expected(role)) for entry in self.entries for role in self.roles
        ]

    def covered_permissions(self) -> frozenset[str]:
        return frozenset(entry.permission for entry in self.entries)

    def uncovered_permissions(self) -> frozenset[str]:
        """
        Permission codes with no row yet.

        Not an error: the matrix grows milestone by milestone as the modules
        that use those codes are built. The test suite reports the number so
        the gap stays visible instead of being forgotten.
        """
        return ALL_PERMISSION_CODES - self.covered_permissions()


def matrix_path() -> Path:
    return Path(str(settings.CURAVIA["PERMISSIONS_MATRIX"]))


@functools.lru_cache(maxsize=1)
def load_matrix() -> Matrix:
    raw = yaml.safe_load(matrix_path().read_text(encoding="utf-8"))
    return _parse(raw)


def _parse(raw: dict[str, Any]) -> Matrix:
    roles = tuple(raw["roles"])
    if len(set(roles)) != len(roles):
        raise ValueError("The matrix lists a role twice.")

    entries: list[MatrixEntry] = []
    for code, spec in (raw.get("permissions") or {}).items():
        if code not in ALL_PERMISSION_CODES:
            raise ValueError(
                f"The matrix mentions permission {code!r}, which does not exist in "
                f"apps.core.permissions. Fix the matrix or add the permission."
            )
        spec = spec or {}
        allow = tuple(spec.get("allow") or ())
        unknown = set(allow) - set(roles)
        if unknown:
            raise ValueError(
                f"Permission {code!r} allows unknown role(s) {sorted(unknown)}. "
                f"Add them to the matrix's `roles` list."
            )
        endpoint_spec = spec.get("endpoint")
        endpoint = (
            Endpoint(
                method=endpoint_spec["method"].upper(),
                url_name=endpoint_spec["url_name"],
                kwargs=endpoint_spec.get("kwargs"),
                allowed_status=int(endpoint_spec.get("allowed_status", 200)),
                denied_status=int(endpoint_spec.get("denied_status", 403)),
            )
            if endpoint_spec
            else None
        )
        entries.append(
            MatrixEntry(
                permission=code,
                allow=frozenset(allow),
                note=spec.get("note", ""),
                endpoint=endpoint,
            )
        )

    return Matrix(version=int(raw.get("version", 1)), roles=roles, entries=tuple(entries))


def as_markdown_table() -> str:
    """
    Render the matrix for the README.

    Roles across the top, permissions down the side, so a reviewer can scan one
    row and see who can verify a lab result.
    """
    matrix = load_matrix()
    header = "| Permission | " + " | ".join(matrix.roles) + " |"
    divider = "|---" * (len(matrix.roles) + 1) + "|"
    lines = [header, divider]
    for entry in matrix.entries:
        cells = ["✓" if entry.expected(role) else "" for role in matrix.roles]
        lines.append(f"| `{entry.permission}` | " + " | ".join(cells) + " |")
    return "\n".join(lines)
